#Requires -Version 5.1
<#
.SYNOPSIS
  Publish bob/worker/dotnet into bob-worker-net.exe (.NET 8 SDK, self-contained win-x64).
.DESCRIPTION
  FR #9800 Phase 0 scaffold. Uses ``dotnet publish`` - not Framework 4 ``csc.exe``.
  Airc min-spec / no-SDK floor does **not** apply. Requires .NET 8 SDK on the build machine.
.OUTPUTS
  Full path of the published bob-worker-net.exe.
#>
[CmdletBinding()]
param(
    [string]$RepoRoot = '',
    [Parameter(Mandatory = $true)][string]$OutDir,
    [string]$Dotnet = '',
    # FR #9800: SHA embedded as AssemblyMetadata SourceCommit for --version.
    [string]$SourceCommit = '',
    [string]$Configuration = 'Release',
    [string]$Runtime = 'win-x64'
)
$ErrorActionPreference = 'Stop'
$cm = Join-Path $PSScriptRoot 'Bobiverse-Common.ps1'
if (-not (Test-Path -LiteralPath $cm)) {
    $cm = Join-Path (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) 'common\scripts\Bobiverse-Common.ps1'
}
. $cm
if (-not $RepoRoot) { $RepoRoot = Get-BobiverseRepoRoot -ScriptDir $PSScriptRoot }

$proj = Get-BobiverseRepoPath -Root $RepoRoot -Rel 'worker\dotnet\BobWorkerNet.csproj'
if (-not $proj -or -not (Test-Path -LiteralPath $proj)) {
    $proj = Join-Path $RepoRoot 'bob\worker\dotnet\BobWorkerNet.csproj'
}
if (-not (Test-Path -LiteralPath $proj)) { throw "missing BobWorkerNet.csproj under bob/worker/dotnet (FR #9800)" }

if (-not $Dotnet) {
    foreach ($c in @(
            (Get-Command dotnet.exe -ErrorAction SilentlyContinue).Source,
            (Join-Path ${env:ProgramFiles} 'dotnet\dotnet.exe'),
            (Join-Path ${env:ProgramFiles(x86)} 'dotnet\dotnet.exe')
        )) {
        if ($c -and (Test-Path -LiteralPath $c)) { $Dotnet = $c; break }
    }
}
if (-not $Dotnet) { throw 'dotnet.exe not found (.NET 8 SDK required for FR #9800; airc no-SDK floor does not apply)' }

# Prefer SourceCommit (explicit > WORKFLOW_COMMIT > git HEAD > unknown)
if (-not $SourceCommit) { $SourceCommit = [string]$env:WORKFLOW_COMMIT }
if (-not $SourceCommit) {
    $prevEapGit = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    $gitOut = & git -C $RepoRoot rev-parse HEAD 2>$null
    $gitCode = $LASTEXITCODE
    $ErrorActionPreference = $prevEapGit
    if ($gitCode -eq 0 -and $gitOut) { $SourceCommit = ([string]$gitOut).Trim() } else { $SourceCommit = '' }
}
if (-not $SourceCommit) { $SourceCommit = 'unknown' }
$SourceCommit = ($SourceCommit -replace '[^0-9a-fA-F]', '').ToLowerInvariant()
if (-not $SourceCommit) { $SourceCommit = 'unknown' }

$publishDir = Join-Path $OutDir 'worker-net-publish'
if (Test-Path -LiteralPath $publishDir) { Remove-Item -LiteralPath $publishDir -Recurse -Force }
New-Item -ItemType Directory -Force -Path $publishDir | Out-Null

Write-Host ("INFO Build-BobWorkerNet SourceCommit={0} Runtime={1}" -f $SourceCommit, $Runtime)

$projDir = Split-Path -Parent $proj
$genPath = Join-Path $projDir 'GeneratedSourceCommit.cs'
$genBackup = Join-Path $publishDir 'GeneratedSourceCommit.cs.bak'
New-Item -ItemType Directory -Force -Path $publishDir | Out-Null
if (Test-Path -LiteralPath $genPath) {
    Copy-Item -LiteralPath $genPath -Destination $genBackup -Force
}
@(
    '// Generated by Build-BobWorkerNet.ps1 (FR #9800); do not edit by hand.'
    'namespace Bobiverse.WorkerNet;'
    ''
    'internal static class GeneratedSourceCommit'
    '{'
    ('    internal const string Value = "{0}";' -f $SourceCommit)
    '}'
) | Set-Content -Encoding ascii -LiteralPath $genPath

# CAST IRON: invoke dotnet publish (never csc.exe).
$argv = @(
    'publish', $proj,
    '-c', $Configuration,
    '-r', $Runtime,
    '--self-contained', 'true',
    '-o', $publishDir,
    '-p:PublishSingleFile=true',
    '-p:IncludeNativeLibrariesForSelfExtract=true'
)
try {
    $prevEap = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    & $Dotnet @argv
    $code = $LASTEXITCODE
    $ErrorActionPreference = $prevEap
    if ($code -ne 0) { throw "dotnet publish failed exit $code (FR #9800)" }
}
finally {
    # Restore placeholder so the worktree stays clean for source control.
    if (Test-Path -LiteralPath $genBackup) {
        Copy-Item -LiteralPath $genBackup -Destination $genPath -Force
    }
    else {
        @(
            '// Placeholder overwritten by Build-BobWorkerNet.ps1 before publish (FR #9800).'
            'namespace Bobiverse.WorkerNet;'
            ''
            'internal static class GeneratedSourceCommit'
            '{'
            '    internal const string Value = "unknown";'
            '}'
        ) | Set-Content -Encoding ascii -LiteralPath $genPath
    }
}

$exe = Join-Path $publishDir 'bob-worker-net.exe'
if (-not (Test-Path -LiteralPath $exe)) { throw "missing published exe: $exe" }

Write-Host ("OK bob-worker-net.exe -> {0}" -f $exe)
return $exe
